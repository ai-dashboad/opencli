def convert(text: str) -> str:
    out = text.translate(CHARACTERS)
    for before, after in WORDS:
        out = out.replace(before, after)
    return out


def main() -> int:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/zh-source.json")
    pairs: dict[str, str] = json.loads(source.read_text(encoding="utf-8"))
    converted = {key: convert(value) for key, value in pairs.items()}
    print(json.dumps(converted, ensure_ascii=False, indent=1))
    return 0


